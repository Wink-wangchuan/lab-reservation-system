1. 实验室须开放且允许预约，任一开关关闭都会被拒。
2. 日期不能早于今天，系统没有「最多提前多少天」的限制。
3. 结束时间须晚于开始时间。
4. 预约时段必须被该实验室当天某个启用的开放时段完整包含。
5. 单次人数不能超过实验室容量，也不能超过所命中时段配置的人数上限（0 表示不限）。
6. 设备故障锁定：实验室下任一设备处于故障状态即整间锁定；指定设备还须属于该实验室且无故障。
7. 时段容量校验：同一时段允许多单共享，把与该区间相交的有效预约按并发峰值累计人数，累计后不得超过实验室容量与时段人数上限，超出时提示剩余可约人数。
