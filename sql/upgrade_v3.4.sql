-- ============================================================================
-- v3.4 时段容量共享：预约从「整间独占」改为「按人数共享」
--
-- 背景：此前的冲突校验只要时段相交就拒绝，3 人预约一间 50 人的实验室也会把
--       余下 47 个位置锁死。新的口径是同一时段允许多单共享，只按累计人数判断：
--         已占用人数 = 目标区间内已有有效预约的「并发人数峰值」
--         实验室容量 / 时段人数上限 - 已占用人数 = 剩余可约人数
--
-- 内容：
--   1. 修正 4 条知识条目（30016 / 30019 / 30051 / 30052 / 30053）的规则描述；
--   2. 无表结构变更，无需数据迁移。
--
-- 幂等：可重复执行。
-- 执行后立即生效：~/opt/redis/bin/redis-cli DEL ai:kb:list
-- ============================================================================

