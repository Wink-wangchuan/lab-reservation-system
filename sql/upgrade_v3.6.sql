--   1. 修正 30018「AI 助手的能力边界」：明确无关请求一律拒绝，且不输出编程代码；
--   2. 无表结构变更。
--
-- 幂等：可重复执行（第二次执行时替换源串已不存在，不会重复追加）。
-- 执行后必做：清 AI 知识库缓存
--   ~/opt/redis/bin/redis-cli DEL ai:kb:list
