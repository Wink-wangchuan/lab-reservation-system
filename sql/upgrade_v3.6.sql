UPDATE ai_knowledge
SET content = REPLACE(content,
        '绕过审批或权限。',
        '绕过审批或权限。\n只回答与本系统相关的问题：写代码、编程作业、翻译、闲聊等无关请求会礼貌拒绝，并引导改问系统内问题；任何情况下都不会输出编程代码。')
WHERE id = 30018;

UPDATE ai_knowledge
SET content = REPLACE(content,
        '3. 与系统无关的通用问题照常回答。',
        '3. 只回答与本系统相关的问题；写代码、编程作业、翻译、闲聊等无关请求会礼貌拒绝，并引导你改问系统内问题。')
WHERE id = 30018;
