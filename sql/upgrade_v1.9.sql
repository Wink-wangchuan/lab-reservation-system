-- 4.1 台账行数（应为 38 条配置）
SELECT COUNT(*) AS device_rows FROM device WHERE deleted = 0;

-- 4.2 设备实际台/套数合计（驾驶舱「设备总数」口径）
SELECT IFNULL(SUM(quantity), 0) AS device_total FROM device WHERE deleted = 0;

-- 4.3 各实验室的配置条目与设备数量
SELECT l.id AS lab_id, l.lab_name, COUNT(d.id) AS configs, IFNULL(SUM(d.quantity), 0) AS qty
FROM lab_info l LEFT JOIN device d ON d.lab_id = l.id AND d.deleted = 0
WHERE l.deleted = 0
GROUP BY l.id, l.lab_name
ORDER BY l.id;

-- 4.4 设备编号重复检查（应为空）
SELECT device_code, COUNT(*) AS c FROM device GROUP BY device_code HAVING c > 1;
